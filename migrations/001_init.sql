CREATE TABLE IF NOT EXISTS applications (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 name TEXT NOT NULL, package_id TEXT NOT NULL, version TEXT,
 description TEXT, source TEXT NOT NULL, path TEXT, icon TEXT,
 update_available INTEGER NOT NULL DEFAULT 0,
 UNIQUE(package_id,source)
);
CREATE TABLE IF NOT EXISTS scan_history(id INTEGER PRIMARY KEY AUTOINCREMENT,status TEXT NOT NULL,application_count INTEGER NOT NULL,started_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS operation_history(id INTEGER PRIMARY KEY AUTOINCREMENT,operation_id TEXT NOT NULL,action TEXT NOT NULL,package_id TEXT NOT NULL,status TEXT NOT NULL,created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS settings(key TEXT PRIMARY KEY,value TEXT NOT NULL);
